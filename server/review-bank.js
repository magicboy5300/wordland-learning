for (const [id, items] of Object.entries(upperReviewBank)) banks[id] = items.map(({ prompt, options, answer, hint, explanation, listen }) => [prompt, options, answer, hint, explanation, listen]);

export const reviewBank = Object.fromEntries(Object.entries(banks).map(([lessonId, values]) => [lessonId, values.map(([prompt, options, answer, hint, explanation, listen], index) => ({
  id: `review-${lessonId}-${index + 1}`, lessonId, type: 'choice', prompt, options, answer, hint, explanation, ...(listen ? { listen } : {}),
}))]));

// Each lesson has a rotating pool. Retrieval cards carry their own reading material.
for (const lesson of [...lessons,...characterLessons]) {
  const originals = reviewBank[lesson.id] || [];
  const retrieval = lesson.questions.map((question, index) => ({ ...question, id: `recall-${lesson.id}-${index + 1}`, lessonId: lesson.id, material: lesson.intro, skillId: question.skillId || question.id, skillLabel: question.skillLabel || question.prompt }));
  reviewBank[lesson.id] = [...originals, ...retrieval];
}
